/** Recompute totals from line items — used by the invoice composer preview. */
export function calculateInvoiceTotals(items, { taxRate = 5, discount = 0 } = {}) {
  const subtotal = items.reduce(
    (sum, item) => sum + Number(item.quantity || 0) * Number(item.unitPrice || 0),
    0,
  );
  const tax = Math.round((subtotal * taxRate) / 100);

  return {
    subtotal,
    taxRate,
    tax,
    discount: Number(discount) || 0,
    total: subtotal + tax - (Number(discount) || 0),
  };
}

export function findInvoice(id) {
  return invoices.find((invoice) => invoice.id === id) || null;
}
